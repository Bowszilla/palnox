export function getPalById(id: string): Pal | undefined {
  return STATIC_PALS.find(p => p.id === id)
}

export function getPalByNumber(num: number): Pal | undefined {
  return STATIC_PALS.find(p => p.palNumber === num)
}

export function searchPals(query: string): Pal[] {
  const q = query.toLowerCase()
  return STATIC_PALS.filter(
    p => p.name.toLowerCase().includes(q) || p.elementPrimary.toLowerCase().includes(q)
  )
}
